-- Per-host + generated modules (~/.config/hypr/<name>.lua).
-- Hyprland's require() already reports errors *inside* a module without
-- aborting the config, but a *missing* file raises — pcall keeps the session
-- usable (default monitors/colors) until install.sh / theme-set create them.
local function optional(name)
    local ok, err = pcall(require, name)
    if not ok then print("hyprland.lua: skipping " .. name .. ": " .. tostring(err)) end
end
optional("env")        -- GPU / Wayland env (NVIDIA etc.); empty on other hosts
optional("monitors")   -- monitor layout (generated by install.sh)
optional("colors")     -- palette borders + shadow (rendered by theme-set)

