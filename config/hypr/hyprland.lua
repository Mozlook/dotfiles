-- --- autostart ---------------------------------------------------------------
hl.on("hyprland.start", function()
    hl.exec_cmd("waybar")
    hl.exec_cmd("swaync")
    hl.exec_cmd("systemctl --user start hyprpolkitagent")
    -- network + bluetooth are handled by the waybar modules (rofi wifi menu /
    -- blueman-manager); the tray applets only duplicated them.
    hl.exec_cmd("wl-paste --watch cliphist store")
    hl.exec_cmd("hypridle")
    -- restore the last theme (wallpaper + colors); also starts the wallpaper daemon
    hl.exec_cmd("~/.local/bin/theme-set \"$(cat ~/.cache/theme/current 2>/dev/null || echo cafe)\"")
    -- terminal on login
    hl.exec_cmd("kitty")
end)

